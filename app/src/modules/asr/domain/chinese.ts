export function toSimplified(text: string): string {
  if (!text) {
    return text;
  }
  try {
    return Array.from(text, (char) => TRADITIONAL_TO_SIMPLIFIED[char] ?? char).join('');
  } catch (cause) {
    // 转换失败不应该让整次识别失败：原文至少还能用
    console.log(`[asr] 繁转简失败：${String(cause)}`);
    return text;
  }
}
